CREATE FUNCTION ascii_lower(value TEXT) RETURNS TEXT LANGUAGE SQL IMMUTABLE STRICT AS $$
  SELECT translate(value, 'ABCDEFGHIJKLMNOPQRSTUVWXYZ', 'abcdefghijklmnopqrstuvwxyz')
$$;
-- Preserve ISO text dates/timestamps exposed by the existing API.
CREATE FUNCTION utc_now() RETURNS TEXT LANGUAGE SQL VOLATILE AS $$
  SELECT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
$$;
CREATE FUNCTION day_number(value TEXT) RETURNS INTEGER LANGUAGE SQL IMMUTABLE STRICT AS $$
  SELECT value::date - DATE '1970-01-01'
$$;
CREATE FUNCTION money_share(amount NUMERIC, numerator NUMERIC, denominator NUMERIC)
RETURNS NUMERIC LANGUAGE SQL IMMUTABLE STRICT AS $$
  SELECT trunc((amount*numerator+trunc(denominator/2))/denominator)
$$;
CREATE FUNCTION can_access_company(company BIGINT) RETURNS BOOLEAN LANGUAGE SQL STABLE AS $$
  SELECT COALESCE(current_setting('paytrack.access',true)::jsonb->>'role'='admin'
    OR (current_setting('paytrack.access',true)::jsonb->'companyIds') @> to_jsonb(company),false)
$$;


CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    cpf TEXT UNIQUE,
    rg TEXT UNIQUE,
    cnh TEXT UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'user' CHECK(role IN ('admin', 'user')),
    access_status TEXT NOT NULL DEFAULT 'pending' CHECK(access_status IN ('pending','active','rejected','blocked')),
    approved_by BIGINT REFERENCES users(id),
    approved_at TEXT,
    rejected_at TEXT,
    blocked_at TEXT,
    password_changed_at TEXT,
    last_login_at TEXT,
    created_at TEXT NOT NULL DEFAULT utc_now(),
    updated_at TEXT NOT NULL DEFAULT utc_now()
);

