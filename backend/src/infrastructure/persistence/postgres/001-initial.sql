CREATE FUNCTION preserve_last_admin() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.role='admin' AND OLD.access_status='active' THEN
    IF TG_OP='DELETE' OR NEW.role<>'admin' OR NEW.access_status<>'active' THEN
      IF (SELECT count(*) FROM users WHERE role='admin' AND access_status='active')<=1 THEN
        RAISE EXCEPTION 'Last active administrator' USING ERRCODE='23514';
      END IF;
    END IF;
  END IF;
  IF TG_OP='DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END $$;
CREATE FUNCTION lock_admin_changes() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  PERFORM pg_advisory_xact_lock(728194001);
  RETURN NULL;
END $$;
CREATE TRIGGER lock_admin_changes BEFORE INSERT OR UPDATE OR DELETE ON users
FOR EACH STATEMENT EXECUTE FUNCTION lock_admin_changes();
CREATE TRIGGER protect_last_admin_update BEFORE UPDATE OF role,access_status ON users
FOR EACH ROW EXECUTE FUNCTION preserve_last_admin();
CREATE TRIGGER protect_last_admin_delete BEFORE DELETE ON users
FOR EACH ROW EXECUTE FUNCTION preserve_last_admin();
CREATE FUNCTION preserve_financial_owner() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF to_jsonb(NEW)->TG_ARGV[0] IS DISTINCT FROM to_jsonb(OLD)->TG_ARGV[0] THEN
    RAISE EXCEPTION 'Financial owner is immutable' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER clients_company_immutable BEFORE UPDATE OF company_id ON clients
