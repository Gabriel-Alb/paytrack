CREATE FUNCTION guard_clients() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP<>'INSERT' AND NOT (can_access_company(OLD.company_id)) THEN
    RAISE EXCEPTION 'Company access denied' USING ERRCODE='23514';
  END IF;
  IF TG_OP<>'DELETE' AND NOT (can_access_company(NEW.company_id)) THEN
    RAISE EXCEPTION 'Company access denied' USING ERRCODE='23514';
  END IF;
  IF TG_OP='DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER guard_clients BEFORE INSERT OR UPDATE OR DELETE ON clients
FOR EACH ROW EXECUTE FUNCTION guard_clients();

