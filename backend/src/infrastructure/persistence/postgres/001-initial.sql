CREATE TABLE IF NOT EXISTS clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
    name TEXT NOT NULL,
    cpf TEXT NOT NULL,
    rg TEXT,
    cnh TEXT,
    phone TEXT,
    email TEXT,
    status TEXT NOT NULL DEFAULT 'sem_contrato'
        CHECK (status IN ('sem_contrato', 'ativo', 'quitado', 'negativado')),
    notes TEXT,
    created_by BIGINT,
    status_override TEXT CHECK (status_override IS NULL OR status_override = 'negativado'),
    created_at TEXT NOT NULL DEFAULT utc_now(),
    updated_at TEXT NOT NULL DEFAULT utc_now(),
    UNIQUE(company_id,cpf),
    UNIQUE(company_id,rg),
    UNIQUE(company_id,cnh),
    FOREIGN KEY (created_by) REFERENCES users(id)
        ON UPDATE CASCADE
        ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS loans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL,
    principal_amount BIGINT NOT NULL CHECK (principal_amount > 0),
    interest_percentage NUMERIC NOT NULL DEFAULT 0 CHECK (interest_percentage >= 0),
    interest_amount BIGINT NOT NULL DEFAULT 0 CHECK (interest_amount >= 0),
    total_amount BIGINT NOT NULL CHECK (total_amount > 0),
    installment_count BIGINT NOT NULL CHECK (installment_count > 0),
    late_fee_per_day BIGINT NOT NULL DEFAULT 0 CHECK (late_fee_per_day >= 0),
    loan_date TEXT NOT NULL,
    first_due_date TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'paid', 'overdue', 'cancelled')),
    notes TEXT,
    created_by BIGINT,
    revision BIGINT NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT utc_now(),
    updated_at TEXT NOT NULL DEFAULT utc_now(),
    FOREIGN KEY (client_id) REFERENCES clients(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    FOREIGN KEY (created_by) REFERENCES users(id)
        ON UPDATE CASCADE
        ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS installments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id BIGINT NOT NULL,
    installment_number BIGINT NOT NULL CHECK (installment_number > 0),
    amount BIGINT NOT NULL CHECK (amount > 0),
    due_date TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'paid', 'overdue', 'partial')),
    paid_amount BIGINT NOT NULL DEFAULT 0 CHECK (paid_amount >= 0),
    paid_at TEXT,
    created_at TEXT NOT NULL DEFAULT utc_now(),
    updated_at TEXT NOT NULL DEFAULT utc_now(),
    UNIQUE (loan_id, installment_number),
    FOREIGN KEY (loan_id) REFERENCES loans(id)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    installment_id BIGINT NOT NULL,
    amount BIGINT NOT NULL CHECK (amount >= 0),
    late_fee_amount BIGINT NOT NULL DEFAULT 0 CHECK (late_fee_amount >= 0),
    payment_date TEXT NOT NULL,
    payment_method TEXT,
    notes TEXT,
    created_by BIGINT,
    created_at TEXT NOT NULL DEFAULT utc_now(),
    voided_at TEXT,
    CHECK (amount > 0 OR late_fee_amount > 0),
    FOREIGN KEY (installment_id) REFERENCES installments(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    FOREIGN KEY (created_by) REFERENCES users(id)
        ON UPDATE CASCADE
        ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS late_fees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    installment_id BIGINT NOT NULL UNIQUE,
    days_late BIGINT NOT NULL DEFAULT 0 CHECK (days_late >= 0),
    amount BIGINT NOT NULL DEFAULT 0 CHECK (amount >= 0),
    paid_amount BIGINT NOT NULL DEFAULT 0 CHECK (paid_amount >= 0),
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'partial', 'paid', 'waived')),
    paid_at TEXT,
    created_at TEXT NOT NULL DEFAULT utc_now(),
    updated_at TEXT NOT NULL DEFAULT utc_now(),
    FOREIGN KEY (installment_id) REFERENCES installments(id)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

